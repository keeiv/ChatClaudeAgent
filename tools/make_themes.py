"""Generate one trusted theme catalogue shared by the native host and embedded UI."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent


def rgb(hex_color):
    return ", ".join(str(int(hex_color[i:i + 2], 16)) for i in (1, 3, 5))


def catalogue():
    source = json.loads((ROOT / "config/themes.json").read_text(encoding="utf-8"))
    css = (ROOT / "ui/app.css").read_text(encoding="utf-8").split(":root {", 1)[1].split("}", 1)[0]
    base = dict(re.findall(r"--([\w-]+):\s*([^;]+);", css))
    for theme in source:
        tokens = dict(base)
        p = theme.pop("palette")
        if p:
            light = theme["scheme"] == "light"
            for key in ("rail", "side", "chat", "panel", "input", "hover", "selected"):
                tokens["bg-" + key] = p[key]
            tokens.update({"bg-float": p["chat"], "bg-embed": p["panel"], "bg-side-hover": p["hover"],
                           "bg-code": p["side"], "border-code": p["line"], "divider": p["line"],
                           "line": p["line"], "text": p["text"], "header": p["text"],
                           "text-muted": p["muted"], "text-faint": p["muted"], "header-2": p["muted"],
                           "icon": p["muted"], "icon-hover": p["text"], "brand": p["brand"],
                           "brand-hover": p["text"], "brand-ink": "#ffffff" if light else p["chat"],
                           "signal": p["signal"], "signal-rgb": rgb(p["signal"]), "link": p["signal"],
                           "signal-soft": f"rgba({rgb(p['signal'])}, .12)",
                           "brand-soft": f"rgba({rgb(p['brand'])}, .08)",
                           "scroll-thumb": p["line"], "gray-btn": p["selected"],
                           "gray-btn-hover": p["hover"], "dot-grid": "transparent",
                           "badge-ink": p["text"], "commander": p["signal"]})
            # Signature colors and system font stacks; the CSS only reads them through these tokens.
            for index, accent in enumerate(p.get("accents", [])[:6], 1):
                tokens["theme-a" + str(index)] = accent
            for key, token in (("font", "font"), ("display", "theme-display"), ("reading", "theme-reading")):
                if p.get(key):
                    tokens[token] = p[key]
            if p.get("ink"):
                tokens["brand-ink"] = p["ink"]
            if light:
                tokens.update({"gemini": "#245db1", "gemini-name": "#245db1", "gemini-rgb": "36, 93, 177"})
                tokens.update({"claude": "#99482f", "claude-name": "#99482f", "codex": "#146948",
                               "codex-name": "#146948", "local1": "#ad3975", "local1-name": "#9a2864",
                               "local2": "#7258a7", "local2-name": "#64439b", "green": "#277743",
                               "red": "#b73541", "yellow": "#89601b", "success-text": "#246b38",
                               "danger-text": "#a62633", "diff-add-text": "#226734",
                               "diff-remove-text": "#a62633", "yellow-rgb": "137, 96, 27",
                               "green-rgb": "39, 119, 67", "red-rgb": "183, 53, 65",
                               "claude-rgb": "153, 72, 47", "codex-rgb": "20, 105, 72",
                               "local1-rgb": "173, 57, 117", "local2-rgb": "114, 88, 167",
                               "badge-copper": "#8d6033", "badge-teal": "#286c65",
                               "badge-steel": "#506a82", "badge-blue": "#38648a"})
        theme["tokens"] = tokens
    return source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    compact = json.dumps(catalogue(), ensure_ascii=False, separators=(",", ":"))
    outputs = {
        ROOT / "ui/theme_catalog.js": "// Generated by tools/make_themes.py; edit config/themes.json.\n"
                                    "'use strict';\nwindow.CCAThemeCatalog = " + compact + ";\n",
        ROOT / "src/theme_catalog.hpp": "// Generated theme data; the UI and native palette share one source.\n"
                                         "#pragma once\n\n// clang-format off\ninline constexpr const char* kThemeCatalog =\n"
                                         + '\n'.join('R"TH(' + compact[i:i + 55] + ')TH"' for i in range(0, len(compact), 55)) + ';\n// clang-format on\n',
    }
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                raise SystemExit("Generated theme catalogue is stale: " + path.name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
